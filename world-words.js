// بانک واژگان مستقل و مفرد ۵ حرفی فارسی + فیلتر هوشمند ضد جمع و مضاف (@chalbazi)
(function(global) {
    function normalizeFaStrict(str) {
        return String(str || '').trim().replace(/\s+/g, '').replace(/\u200c/g, '')
            .replace(/ي/g, 'ی').replace(/ك/g, 'ک')
            .replace(/آ/g, 'ا').replace(/أ/g, 'ا').replace(/إ/g, 'ا')
            .replace(/ة/g, 'ه').replace(/[\u064B-\u065F]/g, '');
    }

    // واژه‌های مفرد اصیلی که به «ات» یا «ان» ختم می‌شوند و جمع نیستند
    var SINGULAR_WHITELIST = new Set([
        "شکلات","ملاقات","مکافات","مناجات","خرابات","ابات","حیات","خیاط","صراط","بساط","نشاط","رباط",
        "باران","تهران","ایران","گیلان","کرمان","زنجان","سمنان","گرگان","کاشان","همدان","دامغان",
        "لارستان","آبادان","بهبهان","زعفران","بادمجان","چمدان","نردبان","آسمان","ریسمان","سایبان",
        "باغبان","پاسبان","میزبان","قهرمان","پهلوان","کاروان","ساربان","مهربان","جاودان","بیابان",
        "خیابان","گلستان","بوستان","شبستان","دبستان","نیستان","کوهستان","تابستان","زمستان","پیمان",
        "فرمان","درمان","ایمان","سامان","دامان","دندان","زندان","خندان","گریان","لرزان","سوزان",
        "تابان","روان","جوان","توان","زبان","جهان","نهان","گران","ارزان","دوران","طوفان","حیوان",
        "انسان","عرفان","ایوان","دیوان","کیهان","میدان","وجدان","بحران","جبران","عمران","هجران",
        "حیران","ویران","پریشان","درخشان","فراوان","نگران","ستوان","استخوان","ارغوان","نوجوان",
        "پشتیبان","دیدبان","مرزبان","سیمان","لیوان","سوهان","کیهان","طغیان","عصیان","نسیان","بنیان"
    ]);

    // بررسی مستقل و مفرد بودن واژه فارسی (رد کردن مضاف مثل «شورای»، «دنیای» و جمع مثل «درختها»، «کتابات»، «پرندگان»)
    function isStandalonePersianWord(rawWord) {
        var w = normalizeFaStrict(rawWord);
        if (w.length < 3 || !/^[ابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی]+$/.test(w)) return false;

        // رد کردن صفت‌ها و اسم‌های مضاف ختم به «ـای» بعد از الف (مثل شورای، دنیای، هوایی/هوای، صدای، بنای)
        if (w.length >= 4 && w.slice(-2) === 'ای') return false;

        // رد کردن کلمات مضاف ختم به «ـوی» بعد از واو (مثل آهوی، بازوی، زانوی، بانوی) به جز واژه‌های اصیل
        if (w.length >= 5 && w.slice(-2) === 'وی' && w !== 'موسوی' && w !== 'رضوی' && w !== 'علوی' && w !== 'نبوی') return false;

        // رد کردن کسره اضافه «ـی» بعد از هـ غیرملفوظ (مثل خانهی / نامهی)
        if (w.length >= 4 && w.slice(-2) === 'هی') return false;

        if (SINGULAR_WHITELIST.has(w)) return true;

        // رد کردن جمع با «ـها»
        if (w.length >= 4 && w.slice(-2) === 'ها') return false;

        // رد کردن جمع با «ـات»
        if (w.length >= 5 && w.slice(-2) === 'ات') return false;

        // رد کردن جمع با «ـان» و «ـگان» (مثل درختان، پرندگان، ستارگان)
        if (w.length >= 5 && w.slice(-2) === 'ان') return false;

        return true;
    }

    var WORDLE_TARGET_WORDS = [
        // طبیعت، آسمان و جغرافیا
        "ستاره","باران","اسمان","مهتاب","ابشار","جزیره","طوفان","دریاچه","کوهسار","جنگل",
        "کویر","ساحل","چشمه","تالاب","جلگه","صخره","تندباد","رگبار","شبنم","سپیده",
        "خورشید","شهاب","سیاره","زهره","مریخ","کیهان","افتاب","نسیم","غروب","طلوع",
        "بهار","پاییز","خرداد","مرداد","اسفند","فروردین","تهران","شیراز","تبریز","کرمان",
        "اهواز","بوشهر","قزوین","گرگان","زنجان","سمنان","کاشان","همدان","ایلام","یاسوج",
        "اراک","ساری","رشت","انزلی","لاهیجان","کیش","قشم","هرمز","البرز","زاگرس",

        // حیوانات و پرندگان
        "پرنده","پروانه","زنبور","زرافه","روباه","گنجشک","کبوتر","دلفین","طاووس","شاهین",
        "قناری","بلبل","کلاغ","لک‌لک","جغد","عقاب","قرقاول","فلامینگو","پنگوئن","شترمرغ",
        "پلنگ","یوزپلنگ","خرگوش","سنجاب","جوجه","گوزن","اهو","ببر","شیر","گرگ",
        "کوسه","نهنگ","لاک‌پشت","قورباغه","مارمولک","عقرب","سنجاقک","کفشدوزک","مورچه","ملخ",

        // خوراکی‌ها، میوه‌ها و گیاهان
        "بادام","انگور","گیلاس","گلابی","ریحان","جعفری","پیتزا","بستنی","شکلات","کلوچه",
        "انجیر","زیتون","چغندر","تربچه","لوبیا","نارنج","لیمو","خرما","پسته","فندق",
        "گردو","زرشک","سماق","دارچین","هل","زعفران","نعناع","ترخون","مرزه","شوید",
        "کرفس","اسفناج","کدو","بادمجان","گوجه","خیار","هویج","شلغم","سیر","پیاز",
        "شقایق","نیلوفر","نرگس","مریم","یاسمن","بنفشه","لاله","رز","اطلسی","اقاقیا",
        "چنار","صنوبر","سپیدار","افرا","بلوط","گردکان","بامبو","کاکتوس","شمعدانی","ارکیده",

        // خانه، اشیا و ابزار
        "پنجره","دیوار","صندلی","لیوان","بشقاب","چنگال","صابون","جوراب","شلوار","چمدان",
        "زنجیر","ترازو","پارچه","پالتو","دستکش","مسواک","ایوان","فانوس","سیمان","پولاد",
        "الماس","یاقوت","فیروز","نقره","برنز","کریستال","اینه","پرده","فرش","گلیم",
        "بالش","پتو","تشک","کمد","قفسه","میز","چراغ","لوستر","ساعت","تقویم",
        "دفتر","مداد","خودکار","پاکن","خط‌کش","پرگار","قیچی","سوزن","نخ","دکمه",
        "کلید","قفل","لولا","دستگیره","شیرآلات","کاشی","سرامیک","اجر","گچ","خشت",
        "چکش","انبر","پیچ","مهره","اره","رنده","سوهان","مته","بیل","کلنگ",

        // مشاغل، هنر و علم
        "نانوا","خیاط","نقاش","عکاس","استاد","شاگرد","مهندس","خلبان","ملوان","سرباز",
        "کارگر","معمار","نجار","اهنگر","سفالگر","زرگر","صحاف","خطاط","شاعر","نویسنده",
        "پزشک","پرستار","داروساز","دندان","وکیل","قاضی","داور","مربی","ورزشکار","قهرمان",
        "گیتار","پیانو","ویولن","سنتور","تار","سهتار","دف","تنبک","نی","فلوت",
        "سینما","تئاتر","موزه","گالری","کتاب","مجله","روزنامه","داستان","رمان","غزل",
        "شطرنج","شناگر","فوتبال","والیبال","کشتی","شمشیر","تیرانداز","کوهنورد","دوچرخه","موتور",

        // مفاهیم، صفات و احساسات اصیل
        "زندگی","لبخند","پیروز","شیرین","دوستی","برادر","خواهر","فرزند","مسافر","مدرسه",
        "میدان","خاموش","ارامش","امروز","دیروز","فردا","خاطره","ترانه","باغچه","بیدار",
        "فرمان","انرژی","طلایی","بلوار","بازار","مغازه","پاساژ","استخر","پرچم","فروشگاه",
        "امید","شادی","نشاط","تلاش","کوشش","همت","غیرت","شجاعت","صداقت","عدالت",
        "مهربان","دلسوز","صبور","فداکار","باهوش","زیرک","چابک","نیرومند","استوار","پایدار",
        "زیبا","قشنگ","دلنشین","دلپذیر","خوشبو","معطر","درخشان","تابان","روشن","شفاف",
        "آزاد","رها","مستقل","سربلند","سرفراز","نیکنام","خوشبخت","سعادتمند","تندرست","سالم"
    ].map(normalizeFaStrict).filter(function(w) {
        return w.length === 5 && isStandalonePersianWord(w);
    });

    // حذف تکراری‌های احتمالی
    WORDLE_TARGET_WORDS = Array.from(new Set(WORDLE_TARGET_WORDS));

    global.normalizeFaStrict = normalizeFaStrict;
    global.isStandalonePersianWord = isStandalonePersianWord;
    global.WORDLE_TARGET_WORDS = WORDLE_TARGET_WORDS;
})(window);
